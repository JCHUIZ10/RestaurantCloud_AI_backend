// =========================================================================
// ÍNDICES EN MEMORIA (O(1) LOOKUPS)
// =========================================================================
const PROVINCIAS_POR_DEP = new Map<string, ProvinciaPeru[]>();
const DISTRITOS_POR_PROV = new Map<string, DistritoPeru[]>();
const DEPARTAMENTOS_MAP = new Map<string, DepartamentoPeru>();
const PROVINCIAS_MAP = new Map<string, ProvinciaPeru>();
const DISTRITOS_MAP = new Map<string, DistritoPeru>();

for (const dep of DEPARTAMENTOS_PERU) {
  DEPARTAMENTOS_MAP.set(dep.codigo, dep);
}

for (const prov of PROVINCIAS_PERU) {
  PROVINCIAS_MAP.set(prov.codigo, prov);
  const list = PROVINCIAS_POR_DEP.get(prov.departamento_codigo);
  if (list) {
    list.push(prov);
  } else {
    PROVINCIAS_POR_DEP.set(prov.departamento_codigo, [prov]);
  }
}

for (const dist of DISTRITOS_PERU) {
  DISTRITOS_MAP.set(dist.codigo, dist);
  const list = DISTRITOS_POR_PROV.get(dist.provincia_codigo);
  if (list) {
    list.push(dist);
  } else {
    DISTRITOS_POR_PROV.set(dist.provincia_codigo, [dist]);
  }
}

/**
 * Obtener provincias filtradas por código de departamento (O(1))
 */
export function getProvinciasByDepartamento(departamentoCodigo: string): ProvinciaPeru[] {
  const provs = PROVINCIAS_POR_DEP.get(departamentoCodigo);
  if (provs && provs.length > 0) {
    return provs;
  }
  const dep = DEPARTAMENTOS_MAP.get(departamentoCodigo);
  return [
    {
      codigo: `${departamentoCodigo}01`,
      departamento_codigo: departamentoCodigo,
      nombre: dep ? dep.nombre : 'Capital',
    },
  ];
}

/**
 * Obtener distritos filtrados por código de provincia (O(1))
 */
export function getDistritosByProvincia(provinciaCodigo: string): DistritoPeru[] {
  const dists = DISTRITOS_POR_PROV.get(provinciaCodigo);
  if (dists && dists.length > 0) {
    return dists;
  }
  const prov = PROVINCIAS_MAP.get(provinciaCodigo);
  return [
    {
      codigo: `${provinciaCodigo}01`,
      provincia_codigo: provinciaCodigo,
      departamento_codigo: provinciaCodigo.substring(0, 2),
      nombre: prov ? prov.nombre : 'Cercado',
    },
  ];
}

/**
 * Buscar la información completa de UBIGEO a partir de un código de distrito (O(1))
 */
export function getUbigeoCompleto(distritoCodigo: string): {
  departamento: DepartamentoPeru;
  provincia: ProvinciaPeru;
  distrito: DistritoPeru;
} | null {
  const dist = DISTRITOS_MAP.get(distritoCodigo);
  if (!dist) return null;

  const prov = PROVINCIAS_MAP.get(dist.provincia_codigo);
  const dep = DEPARTAMENTOS_MAP.get(dist.departamento_codigo);

  if (!prov || !dep) return null;

  return { departamento: dep, provincia: prov, distrito: dist };
}
